"""Career Roadmap endpoints."""

import json
import logging
from typing import Optional, List
from fastapi import APIRouter, Depends, HTTPException, Query, Request
from pydantic import BaseModel, Field
from sqlalchemy.orm import Session

from app.database import get_db
from app.models.roadmap import CareerRoadmapDB
from app.models.user import User
from app.services.career_roadmap_service import generate_career_roadmap
from app.services.gemini_client import is_demo_mode_active
from app.auth import get_current_user

logger = logging.getLogger("careerpilot.api.roadmap")
router = APIRouter(prefix="/api/roadmap", tags=["Career Roadmap"])


class RoadmapRequest(BaseModel):
    target_role: str = Field(..., min_length=2, max_length=120)
    skill_level: str = Field("Beginner", min_length=2, max_length=50)
    existing_skills: Optional[str] = ""
    hours_per_week: int = Field(10, ge=1, le=80)


@router.post("")
def create_roadmap(
    request: Request,
    req: RoadmapRequest,
    demo: bool = Query(False),
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """Generate an AI-powered career roadmap and persist it for the current user."""
    target_role = req.target_role.strip()
    if not target_role:
        raise HTTPException(status_code=400, detail="Target role cannot be empty")

    header_demo = request.headers.get("x-demo-mode", "").lower() in ("true", "1", "yes")
    active_demo = demo or header_demo or is_demo_mode_active()

    try:
        roadmap_data = generate_career_roadmap(
            target_role=target_role,
            skill_level=req.skill_level,
            existing_skills=req.existing_skills or "",
            hours_per_week=req.hours_per_week,
            demo=active_demo,
        )
    except TypeError:
        roadmap_data = generate_career_roadmap(
            target_role=target_role,
            skill_level=req.skill_level,
            existing_skills=req.existing_skills or "",
            hours_per_week=req.hours_per_week,
        )
    roadmap_data["is_demo"] = active_demo

    # Persist roadmap into SQLite database
    try:
        record = CareerRoadmapDB(
            user_id=current_user.id,
            target_role=target_role,
            skill_level=req.skill_level,
            existing_skills=req.existing_skills or "",
            hours_per_week=req.hours_per_week,
            timeline=roadmap_data.get("timeline", ""),
            next_action=roadmap_data.get("recommended_next_action", ""),
            roadmap_json=json.dumps(roadmap_data),
        )
        db.add(record)
        db.commit()
        db.refresh(record)
        roadmap_data["id"] = record.id
        roadmap_data["created_at"] = record.created_at.isoformat() if record.created_at else None
    except Exception as exc:
        logger.error("Failed to save roadmap to database: %s", exc)
        roadmap_data["id"] = None

    return roadmap_data


@router.get("/latest")
def get_latest_roadmap(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """Fetch the latest saved roadmap for the authenticated user."""
    record = (
        db.query(CareerRoadmapDB)
        .filter(CareerRoadmapDB.user_id == current_user.id)
        .order_by(CareerRoadmapDB.created_at.desc())
        .first()
    )
    if not record:
        return {"roadmap": None}

    roadmap = record.get_roadmap()
    roadmap["id"] = record.id
    roadmap["created_at"] = record.created_at.isoformat() if record.created_at else None
    return {"roadmap": roadmap}


@router.get("/history")
def get_roadmap_history(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """Fetch a summary list of past roadmaps generated by the user."""
    records = (
        db.query(CareerRoadmapDB)
        .filter(CareerRoadmapDB.user_id == current_user.id)
        .order_by(CareerRoadmapDB.created_at.desc())
        .all()
    )
    history = []
    for r in records:
        r_data = r.get_roadmap()
        history.append({
            "id": r.id,
            "target_role": r.target_role,
            "skill_level": r.skill_level,
            "timeline": r.timeline,
            "created_at": r.created_at.isoformat() if r.created_at else None,
            "stages_count": len(r_data.get("stages", [])),
            "is_demo": bool(r_data.get("is_demo", False)),
        })
    return {"roadmaps": history, "history": history, "total": len(history)}
